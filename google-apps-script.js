// 19 Master Sheet Columns required by Shri Kanth Finance Service
var HEADERS = [
  "Lead ID",
  "Submission Date",
  "Submission Time",
  "Customer Name",
  "Mobile Number",
  "Email",
  "City",
  "District",
  "Loan Type",
  "Loan Amount",
  "Employment Type",
  "Monthly Income",
  "Existing Loan",
  "Lead Source",
  "Lead Status",
  "Lead Temperature",
  "Assigned Agent",
  "Follow-up Date",
  "Remarks"
];

/**
 * Handle POST requests from Shri Kanth Finance Service server
 */
function doPost(e) {
  var lock = LockService.getScriptLock();
  // Wait up to 30 seconds for concurrent writes to finish
  lock.tryLock(30000);

  try {
    var sheet = getOrCreateMasterSheet();
    var payload;

    if (e && e.postData && e.postData.contents) {
      payload = JSON.parse(e.postData.contents);
    } else if (e && e.parameter) {
      payload = e.parameter;
    } else {
      throw new Error("No payload provided");
    }

    // Required field validation
    if (!payload.customerName || !payload.mobileNumber) {
      return ContentService.createTextOutput(JSON.stringify({
        success: false,
        error: "Missing required fields: customerName and mobileNumber"
      })).setMimeType(ContentService.MimeType.JSON);
    }

    // Server-side timestamp fallback in Indian Standard Time (IST)
    var now = new Date();
    var istDate = Utilities.formatDate(now, "Asia/Kolkata", "yyyy-MM-dd");
    var istTime = Utilities.formatDate(now, "Asia/Kolkata", "HH:mm:ss");

    // Sequential Lead ID if not already generated by backend
    var leadId = payload.leadId;
    if (!leadId) {
      var lastRow = sheet.getLastRow();
      var sequence = Math.max(1, lastRow);
      var padded = ("0000" + sequence).slice(-4);
      leadId = "SKF-2026-" + padded;
    }

    // Prepare row matching the 19 columns exactly
    var rowData = [
      leadId,                                                // Lead ID
      payload.submissionDate || istDate,                     // Submission Date
      payload.submissionTime || istTime,                     // Submission Time
      payload.customerName || "",                            // Customer Name
      payload.mobileNumber || "",                            // Mobile Number
      payload.email || "",                                   // Email
      payload.city || "",                                    // City
      payload.district || "",                                // District
      payload.loanType || "Home Loan",                       // Loan Type
      payload.loanAmount || "",                              // Loan Amount
      payload.employmentType || "Salaried",                  // Employment Type
      payload.monthlyIncome || "",                           // Monthly Income
      payload.existingLoan || "No",                          // Existing Loan
      payload.leadSource || "Website – Apply Now",           // Lead Source
      payload.leadStatus || "New",                           // Lead Status
      payload.leadTemperature || "Warm",                     // Lead Temperature
      payload.assignedAgent || "Unassigned",                 // Assigned Agent
      payload.followUpDate || "",                            // Follow-up Date
      payload.remarks || ""                                  // Remarks
    ];

    // Append to Google Sheet
    sheet.appendRow(rowData);
    var newRowNumber = sheet.getLastRow();

    // Style the new row cleanly
    var newRowRange = sheet.getRange(newRowNumber, 1, 1, HEADERS.length);
    newRowRange.setFontFamily("Arial");
    newRowRange.setFontSize(10);
    newRowRange.setVerticalAlignment("middle");

    return ContentService.createTextOutput(JSON.stringify({
      success: true,
      leadId: leadId,
      rowNumber: newRowNumber,
      message: "Lead successfully recorded in Master Google Sheet"
    })).setMimeType(ContentService.MimeType.JSON);

  } catch (err) {
    return ContentService.createTextOutput(JSON.stringify({
      success: false,
      error: err.toString()
    })).setMimeType(ContentService.MimeType.JSON);

  } finally {
    lock.releaseLock();
  }
}

/**
 * Handle GET requests (for testing and connectivity verification)
 */
function doGet(e) {
  try {
    var sheet = getOrCreateMasterSheet();
    return ContentService.createTextOutput(JSON.stringify({
      status: "ACTIVE",
      service: "Shri Kanth Finance Service Master Lead Database",
      totalLeads: Math.max(0, sheet.getLastRow() - 1),
      timestamp: new Date().toISOString()
    })).setMimeType(ContentService.MimeType.JSON);
  } catch (err) {
    return ContentService.createTextOutput(JSON.stringify({
      status: "ERROR",
      error: err.toString()
    })).setMimeType(ContentService.MimeType.JSON);
  }
}

/**
 * Initialize or get master sheet with styled headers
 */
function getOrCreateMasterSheet() {
  var ss = SpreadsheetApp.getActiveSpreadsheet();
  var sheet = ss.getSheetByName("Master Leads") || ss.getActiveSheet();
  
  if (sheet.getName() !== "Master Leads") {
    try {
      sheet.setName("Master Leads");
    } catch (e) {}
  }

  // If sheet is empty or headers missing, setup header row
  if (sheet.getLastRow() === 0) {
    sheet.appendRow(HEADERS);
    
    // Style headers with Navy Blue (#0B2A4A) and Gold Accent
    var headerRange = sheet.getRange(1, 1, 1, HEADERS.length);
    headerRange.setBackground("#0B2A4A");
    headerRange.setFontColor("#FFFFFF");
    headerRange.setFontWeight("bold");
    headerRange.setFontSize(10);
    headerRange.setHorizontalAlignment("center");
    headerRange.setVerticalAlignment("middle");
    sheet.setRowHeight(1, 36);
    sheet.setFrozenRows(1);

    // Auto-resize columns
    for (var col = 1; col <= HEADERS.length; col++) {
      sheet.setColumnWidth(col, 140);
    }
    sheet.setColumnWidth(1, 130); // Lead ID
    sheet.setColumnWidth(4, 180); // Customer Name
    sheet.setColumnWidth(5, 130); // Mobile
    sheet.setColumnWidth(6, 200); // Email
    sheet.setColumnWidth(14, 210); // Lead Source
    sheet.setColumnWidth(19, 250); // Remarks
  }

  return sheet;
}
